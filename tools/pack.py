"""Select summits and pack them into small JSON tiles for the watch.

Usage: python3 -I pack.py <peaks_merged.json> <project_dir>

Each tile covers TILE_DEG x TILE_DEG degrees and is stored as
    [ ["Name", ...], [latE4, lonE4, elev, prom, massifIdx, ...] ]
so the watch only ever holds one tile plus its short result list in memory.
"""
import json, math, os, sys
from collections import defaultdict

src, proj = sys.argv[1], sys.argv[2]
peaks = json.load(open(src, encoding="utf-8"))

LAT0, LON0, TILE_DEG = 45.75, 5.75, 0.5
ROWS, COLS = 5, 10   # 45.75..48.25, 5.75..10.75

# --- selection: importance = prominence -------------------------------------
# Lists were built with prominence >= 150 m; a handful of famous low-prominence
# viewpoints (Uetliberg, Pic Chaussy, ...) came from single articles (src WP).
sel = [p for p in peaks if p["p"] >= 150 or ("WP" in p["srcs"] and p["p"] >= 100)]
print("selected", len(sel), "of", len(peaks))

massifs = sorted({p["rng"] or "Swiss Prealps" for p in sel})
midx = {m: i for i, m in enumerate(massifs)}

tiles = defaultdict(list)
for p in sel:
    r = int(math.floor((p["lat"] - LAT0) / TILE_DEG))
    c = int(math.floor((p["lon"] - LON0) / TILE_DEG))
    assert 0 <= r < ROWS and 0 <= c < COLS, p
    tiles[(r, c)].append(p)

res = os.path.join(proj, "resources", "tiles")
os.makedirs(res, exist_ok=True)
for f in os.listdir(res):
    os.remove(os.path.join(res, f))

xml = ['<resources>', '    <jsonData id="massifs" filename="massifs.json"/>']
json.dump(massifs, open(os.path.join(res, "massifs.json"), "w", encoding="utf-8"), ensure_ascii=False, separators=(",", ":"))
biggest = 0
for (r, c), lst in sorted(tiles.items()):
    lst.sort(key=lambda p: -p["p"])          # most prominent first
    names = [p["name"] for p in lst]
    data = []
    for p in lst:
        data += [round(p["lat"] * 1e4), round(p["lon"] * 1e4), p["h"], p["p"], midx[p["rng"] or "Swiss Prealps"]]
    fn = f"t_{r}_{c}.json"
    json.dump([names, data], open(os.path.join(res, fn), "w", encoding="utf-8"), ensure_ascii=False, separators=(",", ":"))
    xml.append(f'    <jsonData id="t_{r}_{c}" filename="{fn}"/>')
    biggest = max(biggest, len(lst))
xml.append('</resources>')
open(os.path.join(res, "tiles.xml"), "w", encoding="utf-8").write("\n".join(xml) + "\n")

# --- Monkey C lookup table: tile index -> resource id ------------------------
ids = []
for r in range(ROWS):
    for c in range(COLS):
        ids.append(f"Rez.JsonData.t_{r}_{c}" if (r, c) in tiles else "null")
lines = ",\n            ".join(", ".join(ids[i:i + COLS]) for i in range(0, len(ids), COLS))
mc = f"""// GENERATED by tools/pack.py - do not edit by hand.
import Toybox.Lang;

module TileIndex {{
    const LAT0 = {LAT0}f;
    const LON0 = {LON0}f;
    const DEG = {TILE_DEG}f;
    const ROWS = {ROWS};
    const COLS = {COLS};
    const PEAK_COUNT = {len(sel)};

    // Resource id for tile (row, col), or null when the tile is empty.
    function resourceFor(row as Number, col as Number) as ResourceId? {{
        if (row < 0 || row >= ROWS || col < 0 || col >= COLS) {{
            return null;
        }}
        var ids = [
            {lines}
        ];
        return ids[row * COLS + col] as ResourceId?;
    }}
}}
"""
open(os.path.join(proj, "source", "TileIndex.mc"), "w", encoding="utf-8").write(mc)

# --- human-readable list for the README / checking ---------------------------
with open(os.path.join(proj, "data", "peaks.csv"), "w", encoding="utf-8") as f:
    f.write("name;elevation_m;prominence_m;lat;lon;massif;sources\n")
    for p in sorted(sel, key=lambda p: (p["rng"], -p["p"])):
        f.write(f'{p["name"]};{p["h"]};{p["p"]};{p["lat"]:.4f};{p["lon"]:.4f};{p["rng"]};{"+".join(p["srcs"])}\n')

print("tiles:", len(tiles), "largest tile:", biggest, "peaks")
print("massifs:", len(massifs))
tot = sum(os.path.getsize(os.path.join(res, f)) for f in os.listdir(res) if f.endswith(".json"))
print("tile json total bytes:", tot)
